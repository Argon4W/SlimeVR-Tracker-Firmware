	slime_nvs_context_t*	nvs_context		= NULL;
	slime_gpio_context_t*	gpio_context	= NULL;
	slime_i2c_context_t*	i2c_context		= NULL;
	slime_lcd_context_t*	lcd_context		= NULL;

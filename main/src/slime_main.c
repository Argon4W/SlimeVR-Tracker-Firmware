void cross(
	const	float a_in	[3],
	const	float b_in	[3],
			float c_out	[3]
) {
	c_out[0] = a_in[1] * b_in[2] - a_in[2] * b_in[1];
	c_out[1] = a_in[2] * b_in[0] - a_in[0] * b_in[2];
	c_out[2] = a_in[0] * b_in[1] - a_in[1] * b_in[0];
}

